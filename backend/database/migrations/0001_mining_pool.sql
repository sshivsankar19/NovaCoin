    miner_count INTEGER NOT NULL DEFAULT 0,
    online_miner_count INTEGER NOT NULL DEFAULT 0,
    offline_miner_count INTEGER NOT NULL DEFAULT 0,
    total_hash_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_shares INTEGER NOT NULL DEFAULT 0,
    accepted_shares INTEGER NOT NULL DEFAULT 0,
    rejected_shares INTEGER NOT NULL DEFAULT 0,
    acceptance_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
    active_job_count INTEGER NOT NULL DEFAULT 0,
    completed_job_count INTEGER NOT NULL DEFAULT 0,
    stale_job_count INTEGER NOT NULL DEFAULT 0,
    expired_job_count INTEGER NOT NULL DEFAULT 0,
    blocks_found INTEGER NOT NULL DEFAULT 0,
    gross_rewards NUMERIC(20, 8) NOT NULL DEFAULT 0,
    pool_fees NUMERIC(20, 8) NOT NULL DEFAULT 0,
    miner_rewards NUMERIC(20, 8) NOT NULL DEFAULT 0

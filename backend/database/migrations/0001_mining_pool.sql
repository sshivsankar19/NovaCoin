);

CREATE TABLE IF NOT EXISTS miners (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mining_pool_id INTEGER NOT NULL,
    wallet_address VARCHAR(64) NOT NULL,
    worker_name VARCHAR(100) NOT NULL,
    api_key_hash VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'offline',
    hash_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
    total_shares INTEGER NOT NULL DEFAULT 0,
    accepted_shares INTEGER NOT NULL DEFAULT 0,
    rejected_shares INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS mining_jobs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mining_pool_id INTEGER NOT NULL,
    miner_id INTEGER NOT NULL,
    block_height INTEGER NOT NULL,
    previous_hash VARCHAR(64) NOT NULL,
    target VARCHAR(64) NOT NULL,
    difficulty INTEGER NOT NULL,
    share_difficulty INTEGER NOT NULL,
    share_target VARCHAR(64) NOT NULL,
    block_data JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS mining_shares (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mining_job_id INTEGER NOT NULL,
    miner_id INTEGER NOT NULL,
    nonce INTEGER NOT NULL,
    hash VARCHAR(64) NOT NULL,
    difficulty INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'accepted',

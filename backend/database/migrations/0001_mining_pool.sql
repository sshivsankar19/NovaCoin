-- Referenced ids must be keys before the pool tables can be created.  A
-- malformed legacy table is left alone rather than causing data loss.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'blockchains'::regclass AND contype = 'p'
    ) AND NOT EXISTS (
        SELECT 1 FROM blockchains WHERE id IS NULL
    ) THEN
        ALTER TABLE blockchains ADD CONSTRAINT pk_blockchains PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'blocks'::regclass AND contype = 'p'
    ) AND NOT EXISTS (
        SELECT 1 FROM blocks WHERE id IS NULL
    ) THEN
        ALTER TABLE blocks ADD CONSTRAINT pk_blocks PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'wallets'::regclass AND contype = 'p'
    ) AND NOT EXISTS (
        SELECT 1 FROM wallets WHERE id IS NULL
    ) THEN
        ALTER TABLE wallets ADD CONSTRAINT pk_wallets PRIMARY KEY (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'transactions'::regclass AND contype = 'p'
    ) AND NOT EXISTS (
        SELECT 1 FROM transactions WHERE id IS NULL
    ) THEN
        ALTER TABLE transactions ADD CONSTRAINT pk_transactions PRIMARY KEY (id);
    END IF;
END
$$;

-- PostgreSQL cannot add NOT NULL to a populated legacy table without a
-- value.  Only tighten the column when there are no existing NULLs.
DO $$
DECLARE
    definition RECORD;
BEGIN
    FOR definition IN
        SELECT *
        FROM (VALUES
            ('blockchains', 'name'),
            ('blockchains', 'symbol'),
            ('blockchains', 'algorithm'),
            ('blockchains', 'difficulty'),
            ('blockchains', 'block_reward'),
            ('blockchains', 'is_active'),
            ('blockchains', 'created_at'),
            ('blocks', 'blockchain_id'),
            ('blocks', 'height'),
            ('blocks', 'hash'),
            ('blocks', 'previous_hash'),
            ('blocks', 'nonce'),
            ('blocks', 'difficulty'),
            ('blocks', 'timestamp'),
            ('wallets', 'address'),
            ('wallets', 'public_key'),
            ('wallets', 'created_at'),
            ('wallets', 'is_active'),
            ('transactions', 'txid'),
            ('transactions', 'blockchain_id'),
            ('transactions', 'sender'),
            ('transactions', 'receiver'),
            ('transactions', 'amount'),
            ('transactions', 'timestamp'),
            ('transactions', 'status')
        ) AS required(table_name, column_name)
    LOOP
        EXECUTE format(
            'DO $inner$ BEGIN
                 IF NOT EXISTS (
                     SELECT 1 FROM %I WHERE %I IS NULL
                 ) THEN
                     ALTER TABLE %I ALTER COLUMN %I SET NOT NULL;
                 END IF;
             EXCEPTION WHEN undefined_column THEN NULL;
             END $inner$',
            definition.table_name, definition.column_name,
            definition.table_name, definition.column_name
        );
    END LOOP;
END
$$;

-- Preserve the uniqueness guarantees of the core SQLAlchemy models.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_blockchains_symbol')
       AND NOT EXISTS (
           SELECT 1
           FROM pg_index idx
           JOIN pg_attribute attr
             ON attr.attrelid = idx.indrelid
            AND attr.attnum = ANY(idx.indkey)
           WHERE idx.indrelid = 'blockchains'::regclass
             AND idx.indisunique
             AND idx.indnkeyatts = 1
             AND attr.attname = 'symbol'
       )
       AND NOT EXISTS (
           SELECT symbol FROM blockchains
           WHERE symbol IS NOT NULL GROUP BY symbol HAVING COUNT(*) > 1
       ) THEN
        ALTER TABLE blockchains ADD CONSTRAINT uq_blockchains_symbol UNIQUE (symbol);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_blocks_hash')
       AND NOT EXISTS (
           SELECT 1
           FROM pg_index idx
           JOIN pg_attribute attr
             ON attr.attrelid = idx.indrelid
            AND attr.attnum = ANY(idx.indkey)
           WHERE idx.indrelid = 'blocks'::regclass
             AND idx.indisunique
             AND idx.indnkeyatts = 1
             AND attr.attname = 'hash'
       )
       AND NOT EXISTS (
           SELECT hash FROM blocks
           WHERE hash IS NOT NULL GROUP BY hash HAVING COUNT(*) > 1
       ) THEN
        ALTER TABLE blocks ADD CONSTRAINT uq_blocks_hash UNIQUE (hash);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_blockchain_height')
       AND NOT EXISTS (
           SELECT blockchain_id, height FROM blocks
           WHERE blockchain_id IS NOT NULL AND height IS NOT NULL
           GROUP BY blockchain_id, height HAVING COUNT(*) > 1
       ) THEN
        ALTER TABLE blocks ADD CONSTRAINT uq_blockchain_height
            UNIQUE (blockchain_id, height);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_wallets_address')
       AND NOT EXISTS (
           SELECT 1
           FROM pg_index idx
           JOIN pg_attribute attr
             ON attr.attrelid = idx.indrelid
            AND attr.attnum = ANY(idx.indkey)
           WHERE idx.indrelid = 'wallets'::regclass
             AND idx.indisunique
             AND idx.indnkeyatts = 1
             AND attr.attname = 'address'
       )
       AND NOT EXISTS (
           SELECT address FROM wallets
           WHERE address IS NOT NULL GROUP BY address HAVING COUNT(*) > 1
       ) THEN
        ALTER TABLE wallets ADD CONSTRAINT uq_wallets_address UNIQUE (address);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_transactions_txid')
       AND NOT EXISTS (
           SELECT 1
           FROM pg_index idx
           JOIN pg_attribute attr
             ON attr.attrelid = idx.indrelid
            AND attr.attnum = ANY(idx.indkey)
           WHERE idx.indrelid = 'transactions'::regclass
             AND idx.indisunique
             AND idx.indnkeyatts = 1
             AND attr.attname = 'txid'
       )
       AND NOT EXISTS (
           SELECT txid FROM transactions
           WHERE txid IS NOT NULL GROUP BY txid HAVING COUNT(*) > 1
       ) THEN
        ALTER TABLE transactions ADD CONSTRAINT uq_transactions_txid UNIQUE (txid);
    END IF;
END
$$;

-- Restore the model foreign keys when they are absent.  Matching existing
-- foreign keys are left untouched, even when their legacy names differ.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'blocks'::regclass
          AND confrelid = 'blockchains'::regclass
          AND contype = 'f'
    ) AND NOT EXISTS (
        SELECT 1 FROM blocks child
        LEFT JOIN blockchains parent ON parent.id = child.blockchain_id
        WHERE child.blockchain_id IS NOT NULL AND parent.id IS NULL
    ) THEN
        ALTER TABLE blocks
            ADD CONSTRAINT fk_blocks_blockchain
            FOREIGN KEY (blockchain_id) REFERENCES blockchains(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'transactions'::regclass
          AND confrelid = 'blockchains'::regclass
          AND contype = 'f'
    ) AND NOT EXISTS (
        SELECT 1 FROM transactions child
        LEFT JOIN blockchains parent ON parent.id = child.blockchain_id
        WHERE child.blockchain_id IS NOT NULL AND parent.id IS NULL
    ) THEN
        ALTER TABLE transactions
            ADD CONSTRAINT fk_transactions_blockchain
            FOREIGN KEY (blockchain_id) REFERENCES blockchains(id);
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'transactions'::regclass
          AND confrelid = 'blocks'::regclass
          AND contype = 'f'
    ) AND NOT EXISTS (
        SELECT 1 FROM transactions child
        LEFT JOIN blocks parent ON parent.id = child.block_id
        WHERE child.block_id IS NOT NULL AND parent.id IS NULL
    ) THEN
        ALTER TABLE transactions
            ADD CONSTRAINT fk_transactions_block
            FOREIGN KEY (block_id) REFERENCES blocks(id);
    END IF;
END
$$;

-- Mining-pool tables.  All defaults match the SQLAlchemy models' defaults.
CREATE TABLE IF NOT EXISTS mining_pools (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(20) NOT NULL,
    algorithm VARCHAR(50) NOT NULL,
    blockchain_id INTEGER NOT NULL,
    fee_percent NUMERIC(5, 2) NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

-- Mining-pool schema.
--
-- This migration is deliberately additive.  Neon databases created by an
-- earlier version of the application already contain the blockchain tables,
-- while a new database contains none of them.  CREATE/ALTER ... IF NOT
-- EXISTS lets both shapes converge without dropping or rewriting data.

-- The pool tables reference these two existing application tables.  Creating
-- them here also makes a completely empty database a valid starting point.
CREATE TABLE IF NOT EXISTS blockchains (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(20) NOT NULL UNIQUE,
    algorithm VARCHAR(50) NOT NULL,
    difficulty INTEGER NOT NULL,
    block_reward DOUBLE PRECISION NOT NULL,
    block_time INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS blocks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blockchain_id INTEGER NOT NULL,
    height INTEGER NOT NULL,
    hash VARCHAR(64) NOT NULL UNIQUE,
    previous_hash VARCHAR(64) NOT NULL,
    nonce INTEGER NOT NULL,
    difficulty INTEGER NOT NULL,
    timestamp TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS wallets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(64) NOT NULL UNIQUE,
    public_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txid VARCHAR(64) NOT NULL UNIQUE,
    blockchain_id INTEGER NOT NULL,
    block_id INTEGER,
    sender VARCHAR(64) NOT NULL,
    receiver VARCHAR(64) NOT NULL,
    amount NUMERIC(38, 18) NOT NULL,
    timestamp TIMESTAMPTZ NOT NULL,
    signature TEXT,
    public_key TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
);

